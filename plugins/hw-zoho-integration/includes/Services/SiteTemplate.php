/**
 * Stage 2 (v1 booking site): apply a booking-page template to a freshly-created
 * couple subsite so it comes out as a working booking site instead of a bare
 * default WordPress install.
 *
 * Replicates the manual "STEPS TO CREATE A WEBSITE" 5-9 (theme, pages, menu,
 * nav widget, static homepage) PLUS the booking-critical Wedding Settings:
 * it clones, from a designated template blog, the theme + the template's pages
 * (Elementor data + page templates) + the nav menu + the static-front-page
 * setting + the DEFAULT hw_* booking settings; then sets the wedding-specific
 * options (Zoho wedding id, a default deposit) so the booking form functions and
 * links back to Zoho.
 *
 * The template blog id is read from the network option
 * 'hw_booking_template_blog_id'. If it is unset/invalid, apply() is a NO-OP, so
 * couple-site creation behaves exactly as before until a template is configured.
 */
class SiteTemplate {

    /** hw_* option keys that are the SAME for every wedding (copied from the template). */
    const DEFAULT_OPTION_KEYS = array(
        'hw_enable_payment', 'hw_min_nights', 'hw_insurance', 'hw_enable_inventory',
        'hw_deposit_type', 'hw_deposit_nights_multiplier', 'hw_service_fee_child',
        'hw_default_quote_availability', 'hw_default_quote_status', 'hw_force_quote_status',
        'hw_enable_teen', 'hw_enable_2_child', 'hw_enable_2_teen', 'hw_enable_basic_price',
        'hw_enable_dynamic_prices', 'hw_ages', 'hw_theme', 'hw_label_rates_disclosure',
        'hw_booking_form_hide_login_cta', 'hw_enable_additional_notes',
        'hw_additional_notes_label', 'hw_additional_notes_required',
        // the agency's guest choices on the booking form, and the Classic auto-charge opt-in
        'hw_insurance_decline_text', 'hw_bed_preferences', 'hw_transfer_optional', 'hw_extra_checkboxes',
        'hw_cv_autocharge',
    );

    /** Per-page meta we never copy when cloning (regenerated by WP/Elementor). */
    const SKIP_META = array( '_edit_lock', '_edit_last', '_elementor_css', '_elementor_page_assets' );

    /**
     * Network options holding each site style's template blog id. The Classic
     * booking template stays on the original key for back-compat.
     */
    const TEMPLATE_OPTION = array(
        'classic'   => 'hw_booking_template_blog_id',
        'promocode' => 'hw_promocode_template_blog_id',
        'fullsite'  => 'hw_fullsite_template_blog_id',
    );

    /** Map a Deal Booking_Model value -> a site style key. */
    public static function style_for_booking_model( $booking_model ) {
        $bm = strtolower( (string) $booking_model );
        if ( strpos( $bm, 'full' ) !== false )                                   return 'fullsite';
        if ( strpos( $bm, 'promocode' ) !== false || strpos( $bm, 'finest' ) !== false
             || strpos( $bm, 'excellence' ) !== false )                          return 'promocode';
        return 'classic';
    }

    /**
     * Apply the configured template for the given SITE STYLE to a new subsite.
     *
     * @param int    $new_blog_id the freshly-created couple subsite blog id
     * @param string $style       'classic' | 'promocode' | 'fullsite' (default classic)
     * @return true|\WP_Error  true on success (incl. the no-op case), WP_Error on a hard failure
     */
    public static function apply( $new_blog_id, $style = 'classic' ) {

        $new_blog_id = (int) $new_blog_id;
        $option_key  = self::TEMPLATE_OPTION[ $style ] ?? self::TEMPLATE_OPTION['classic'];
        $template_blog_id = (int) get_network_option( null, $option_key, 0 );
        // promocode/fullsite fall back to the classic template if their own isn't
        // configured yet (so a half-set-up network still produces a working site).
        if ( ! $template_blog_id && $style !== 'classic' ) {
            $template_blog_id = (int) get_network_option( null, self::TEMPLATE_OPTION['classic'], 0 );
        }

        if ( ! $template_blog_id ) {
            // phase4-template-required: an unthemed live couple site is a silent failure; fail loudly unless the network opts out.
            if ( (int) get_network_option( null, 'hw_site_template_optional', 0 ) === 1 ) {
                return true;
            }
            error_log( '[SITE-TEMPLATE] no template blog configured for style ' . $style . ' (set hw_booking_template_blog_id, or hw_site_template_optional=1 to allow unthemed sites)' );
            return new \WP_Error( 'TEMPLATE_UNSET', 'No couple-site template is configured for style "' . $style . '". Set the template blog id (network option) before creating sites, or set hw_site_template_optional=1.' );

}
        if ( $new_blog_id === $template_blog_id ) {
            return new \WP_Error( 'TEMPLATE_SELF', 'Refusing to apply the template to the template blog itself.' );
        }

        // ---- read the template ----
        switch_to_blog( $template_blog_id );

        $theme_stylesheet = get_option( 'stylesheet' );
        $theme_template   = get_option( 'template' );
        $src_name         = (string) get_option( 'blogname' );
        $front_src        = (int) get_option( 'page_on_front' );

        $pages = array();
        $tpl_pages = get_posts( array(
            'post_type'   => 'page',
            'post_status' => 'publish',
            'numberposts' => -1,
            'orderby'     => 'menu_order',
            'order'       => 'ASC',
        ) );
        foreach ( $tpl_pages as $p ) {
            if ( 'sample-page' === $p->post_name ) {
                continue; // skip the default WP "Sample Page"
            }
            $meta = array();
            foreach ( get_post_meta( $p->ID ) as $k => $vals ) {
                if ( in_array( $k, self::SKIP_META, true ) ) {
                    continue;
                }
                $meta[ $k ] = get_post_meta( $p->ID, $k, true );
            }
            $pages[ $p->ID ] = array( 'post' => $p, 'meta' => $meta );
        }

        // nav menus (each menu term + its items), the location assignments, and
        // the widget setup (the header nav is an Offcanvas "Navigation Menu" widget).
        $src_menus = array();
        foreach ( wp_get_nav_menus() as $m ) {
            $items = wp_get_nav_menu_items( $m->term_id );
            $list  = array();
            if ( $items ) {
                foreach ( $items as $it ) {
                    $list[] = array(
                        'title'     => $it->title,
                        'object'    => $it->object,
                        'object_id' => (int) $it->object_id,
                        'type'      => $it->type,
                        'url'       => $it->url,
                    );
                }
            }
            $src_menus[ (int) $m->term_id ] = array( 'name' => $m->name, 'items' => $list );
        }
        $src_locations  = get_nav_menu_locations();      // location => menu term id (theme_mod)
        $src_sidebars   = get_option( 'sidebars_widgets' );
        $src_widget_nav = get_option( 'widget_nav_menu' );

        $settings = array();
        foreach ( self::DEFAULT_OPTION_KEYS as $k ) {
            $v = get_option( $k, '__HW_NONE__' );
            if ( '__HW_NONE__' !== $v ) {
                $settings[ $k ] = $v;
            }
        }

        restore_current_blog();

        // ---- write the new site ----
        switch_to_blog( $new_blog_id );

        $dst_name = (string) get_option( 'blogname' );

        // Substitutions applied to cloned page content/Elementor data so a
        // genericized template auto-fills this wedding's data. Templates should
        // use the {{COUPLE_NAME}} / {{WEDDING_DATE}} placeholders; the legacy
        // full-name swap is kept as a fallback for non-genericized templates.
        $dst_date_raw = get_option( 'hw_date' );
        $dst_date_fmt = $dst_date_raw ? date_i18n( 'F j, Y', strtotime( $dst_date_raw ) ) : '';
        // promocode sites also show the group's TRAVEL PERIOD (rate-valid dates) and
        // BOOKING WINDOW end (last day the promo code applies), built from the wedding.
        $ts = get_option( 'hw_start_date' ); $te = get_option( 'hw_end_date' );
        $travel_period = self::format_date_range( $ts, $te );
        $bw = get_option( 'hw_date_unavailable' );
        $booking_window = $bw ? date_i18n( 'F j, Y', strtotime( $bw ) ) : '';
        $replacements = array(
            '{{COUPLE_NAME}}'    => $dst_name,
            '{{WEDDING_DATE}}'   => $dst_date_fmt,
            // promocode sites: the template holds {{PROMOCODE}}; fill this couple's code
            '{{PROMOCODE}}'      => (string) get_option( 'hw_promocode' ),
            '{{TRAVEL_PERIOD}}'  => $travel_period,
            '{{BOOKING_WINDOW}}' => $booking_window,
        );
        if ( '' !== $src_name && $src_name !== $dst_name ) {
            $replacements[ $src_name ] = $dst_name;
        }

        update_option( 'stylesheet', $theme_stylesheet );
        update_option( 'template', $theme_template );

        foreach ( $settings as $k => $v ) {
            update_option( $k, $v );
        }

        // wedding-specific: link the booking form to this wedding's Zoho deal.
        $wid = get_option( 'hwzi_wedding_id' );
        if ( $wid && ! get_option( 'hwz_wedding_id' ) ) {
            update_option( 'hwz_wedding_id', $wid );
        }
        if ( ! get_option( 'hw_min_deposit' ) ) {
            update_option( 'hw_min_deposit', '200' );
        }

        // clone the template's pages
        $map = array();
        foreach ( $pages as $old_id => $data ) {
            $po = $data['post'];
            $new_id = wp_insert_post( array(
                'post_title'   => $po->post_title,
                'post_name'    => $po->post_name,
                'post_content' => strtr( $po->post_content, $replacements ),
                'post_status'  => 'publish',
                'post_type'    => 'page',
                'post_author'  => 1,
                'menu_order'   => $po->menu_order,
            ) );
            if ( is_wp_error( $new_id ) || ! $new_id ) {
                continue;
            }
            $map[ $old_id ] = $new_id;
            foreach ( $data['meta'] as $k => $v ) {
                if ( '_elementor_data' === $k && is_string( $v ) ) {
                    $v = strtr( $v, $replacements );
                }
                // update_post_meta() runs wp_unslash() on the value, but get_post_meta()
                // above already returned it UNslashed. Writing it raw double-unslashes,
                // stripping every backslash in the content — which turns Elementor's
                // JSON unicode escapes (" " nbsp, "\uXXXX") and escaped quotes
                // ("\"") into literal text ("u00a0") on the cloned page. wp_slash()
                // compensates so the escape survives the write intact.
                update_post_meta( $new_id, $k, wp_slash( $v ) );
            }
        }

        // static front page
        update_option( 'show_on_front', 'page' );
        if ( $front_src && isset( $map[ $front_src ] ) ) {
            update_option( 'page_on_front', $map[ $front_src ] );
            // Cosmetic hero prepend triggers Elementor Pro's notes hooks, which
            // query a per-site e_notes table that doesn't exist on a brand-new
            // subsite -> a fatal that would otherwise abort apply() AFTER the
            // theme/pages are set but leave the site half-templated. Never let it
            // break the core templating.
            try {
                self::prepend_resort_hero( $map[ $front_src ] );
            } catch ( \Throwable $e ) {
                error_log( '[hw-zoho] resort hero prepend skipped for blog ' . $new_blog_id . ': ' . $e->getMessage() );
            }
        }

        // recreate each template menu (remapping cloned page ids); track old->new term ids
        $menu_map = array();
        foreach ( $src_menus as $old_term => $mdata ) {
            $existing = wp_get_nav_menu_object( $mdata['name'] );
            if ( $existing ) {
                wp_delete_nav_menu( $existing->term_id );
            }
            $new_term = wp_create_nav_menu( $mdata['name'] );
            if ( is_wp_error( $new_term ) ) {
                continue;
            }
            $menu_map[ $old_term ] = (int) $new_term;
            foreach ( $mdata['items'] as $it ) {
                $oid = $it['object_id'];
                if ( 'post_type' === $it['type'] && isset( $map[ $oid ] ) ) {
                    $oid = $map[ $oid ];
                }
                wp_update_nav_menu_item( $new_term, 0, array(
                    'menu-item-title'     => $it['title'],
                    'menu-item-object'    => $it['object'],
                    'menu-item-object-id' => $oid,
                    'menu-item-type'      => $it['type'],
                    'menu-item-url'       => $it['url'],
                    'menu-item-status'    => 'publish',
                ) );
            }
        }

        // assign menu locations (remapped to the new menu term ids)
        $new_locations = array();
        foreach ( (array) $src_locations as $loc => $old_term ) {
            if ( $old_term && isset( $menu_map[ $old_term ] ) ) {
                $new_locations[ $loc ] = $menu_map[ $old_term ];
            }
        }
        if ( $new_locations ) {
            set_theme_mod( 'nav_menu_locations', $new_locations );
        }

        // copy the widget layout (incl. the Offcanvas nav widget) and point the
        // Navigation Menu widget instances at the recreated menus.
        if ( is_array( $src_sidebars ) ) {
            update_option( 'sidebars_widgets', $src_sidebars );
        }
        if ( is_array( $src_widget_nav ) ) {
            $new_widget_nav = array();
            foreach ( $src_widget_nav as $idx => $inst ) {
                if ( '_multiwidget' === $idx ) {
                    $new_widget_nav[ $idx ] = $inst;
                    continue;
                }
                if ( is_array( $inst ) && isset( $inst['nav_menu'] ) && isset( $menu_map[ $inst['nav_menu'] ] ) ) {
                    $inst['nav_menu'] = $menu_map[ $inst['nav_menu'] ];
                }
                $new_widget_nav[ $idx ] = $inst;
            }
            update_option( 'widget_nav_menu', $new_widget_nav );
        }

        restore_current_blog();

        // a new site takes part in the pending-charge check (cv-pending-cron.php) from day one
        $host = (string) parse_url( get_home_url( $new_blog_id ), PHP_URL_HOST );
        if ( $host !== '' ) {
            $sites = array_filter( array_map( 'trim', explode( ',', (string) get_network_option( null, 'hw_cv_cron_sites', '' ) ) ) );
            if ( ! in_array( $host, $sites, true ) ) {
                $sites[] = $host;
                update_network_option( null, 'hw_cv_cron_sites', implode( ',', $sites ) );
            }
        }

        return true;
    }

    /**
     * Prepend a full-width resort hero (background image) to the front page's
     * Elementor data, using this wedding's hotel image from the resort API.
     * Idempotent: removes a previously-injected hero first. Silent no-op on any
     * missing piece (no hotel id / API down / unparseable data).
     *
     * @param int $page_id  the cloned front (Home) page id, in the new blog context
     */
    private static function prepend_resort_hero( $page_id ) {

        if ( ! $page_id || ! function_exists( 'hw' ) ) {
            return;
        }
        $hotel_id = get_option( 'hw_hotel_id' );
        if ( ! $hotel_id ) {
            return;
        }
        $conn = hw()->getApiConnection();
        if ( ! $conn ) {
            return;
        }
        $resp = $conn->get( 'hotel/' . $hotel_id );
        if ( ! is_object( $resp ) || ! $resp->isSuccess() ) {
            return;
        }
        $hotel = $resp->getData();
        $image = ! empty( $hotel['main_image'] ) ? $hotel['main_image']
               : ( ! empty( $hotel['images'][0] ) ? $hotel['images'][0] : '' );
        if ( ! $image ) {
            return;
        }

        $raw  = get_post_meta( $page_id, '_elementor_data', true );
        $data = json_decode( $raw, true );
        if ( ! is_array( $data ) ) {
            $data = json_decode( wp_unslash( $raw ), true );
        }
        if ( ! is_array( $data ) ) {
            return;
        }

        if ( empty( $data ) ) {
            return;
        }

        // drop any previously-injected empty hero, then turn the FIRST section
        // (the date section) INTO the hero: resort background image, taller, and
        // its heading(s) in white so the wedding date sits ON the photo.
        $data = array_values( array_filter( $data, function ( $s ) {
            return ! ( isset( $s['id'] ) && 'herobg01' === $s['id'] );
        } ) );
        if ( empty( $data ) ) {
            return;
        }

        $data[0]['settings']['background_background']        = 'classic';
        $data[0]['settings']['background_image']             = array( 'url' => $image, 'id' => '' );
        $data[0]['settings']['background_position']          = 'center center';
        $data[0]['settings']['background_size']              = 'cover';
        $data[0]['settings']['background_repeat']            = 'no-repeat';
        $data[0]['settings']['height']                       = 'min-height';
        // 40vh: tall enough for the date-on-photo hero, short enough that the top
        // of the booking content is visible without scrolling.
        $data[0]['settings']['custom_height']                = array( 'unit' => 'vh', 'size' => 40, 'sizes' => array() );
        $data[0]['settings']['content_position']             = 'middle';
        $data[0]['settings']['background_overlay_background'] = 'classic';
        $data[0]['settings']['background_overlay_color']     = 'rgba(0,0,0,0.3)';
        self::whiten_headings( $data[0] );

        update_post_meta( $page_id, '_elementor_data', wp_slash( wp_json_encode( $data ) ) );
        delete_post_meta( $page_id, '_elementor_element_cache' );
        delete_post_meta( $page_id, '_elementor_css' );
    }

    /**
     * Format a start/end date pair as a human "travel period" string:
     *   same month  -> "June 23-30, 2027"
     *   same year    -> "June 23 - July 2, 2027"
     *   cross year   -> "December 29, 2027 - January 3, 2028"
     * Returns '' if either date is missing/unparseable.
     */
    private static function format_date_range( $start, $end ) {
        $start = trim( (string) $start ); $end = trim( (string) $end );
        if ( '' === $start || '' === $end ) {
            return '';
        }
        $s = strtotime( $start ); $e = strtotime( $end );
        if ( ! $s || ! $e ) {
            return '';
        }
        if ( $e < $s ) { $t = $s; $s = $e; $e = $t; }
        if ( date( 'Y', $s ) !== date( 'Y', $e ) ) {
            return date_i18n( 'F j, Y', $s ) . ' - ' . date_i18n( 'F j, Y', $e );
        }
        if ( date( 'n', $s ) === date( 'n', $e ) ) {
            return date_i18n( 'F j', $s ) . '-' . date_i18n( 'j, Y', $e );
        }
        return date_i18n( 'F j', $s ) . ' - ' . date_i18n( 'F j, Y', $e );
    }

    /** Recursively set heading widgets' title colour to white (hero overlay text). */
    private static function whiten_headings( &$element ) {
        if ( isset( $element['widgetType'] ) && 'heading' === $element['widgetType'] ) {
            $element['settings']['title_color'] = '#FFFFFF';
        }
        if ( ! empty( $element['elements'] ) && is_array( $element['elements'] ) ) {
            foreach ( $element['elements'] as &$child ) {
                self::whiten_headings( $child );
            }
        }
    }
}
